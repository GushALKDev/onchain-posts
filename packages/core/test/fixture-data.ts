import { buildBatch, inclusionProof, postHash, sigCommit } from '../src/index.ts';
import { sampleArweaveId, sampleIntent, samplePost, userAccount } from './helpers.ts';
import { POSTS_DOMAIN, POST_TYPES } from '../src/index.ts';

export const FIXTURE_PATH = new URL('./fixtures/merkle-fixture.json', import.meta.url);

/**
 * Merkle fixture shared with the Solidity tests (contracts/test/CoreFixture.t.sol): 7 real posts signed with a test
 * key, an odd count so the tree is unbalanced. Solidity rebuilds the root and checks every proof against PostAnchor.
 */
export async function buildMerkleFixture() {
  const entries = [];
  for (let i = 0; i < 7; i++) {
    const post = samplePost(i, i % 3 !== 0);
    const signature = await userAccount.signTypedData({ domain: POSTS_DOMAIN, types: POST_TYPES, primaryType: 'PublishIntent', message: sampleIntent(post, i) });
    entries.push({ postHash: postHash(post), postArweaveId: sampleArweaveId(`post ${i}`), sigCommit: sigCommit(signature) });
  }
  const { manifest, tree } = buildBatch(84532, entries);
  return {
    description: 'Generated by packages/core/scripts/generate-fixtures.ts. Do not edit by hand.',
    root: manifest.root,
    count: entries.length,
    leaves: entries.map((entry) => ({ ...entry, ...inclusionProof(tree, entry.postHash)! })),
  };
}

export const serialize = (fixture: unknown) => `${JSON.stringify(fixture, null, 2)}\n`;
